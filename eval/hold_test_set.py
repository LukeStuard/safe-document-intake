"""Puts the held-out eval test set on hold in the live D1, so the backfill never screens it before Phase 4.

Reads eval/test/load_result.json (written by load.py) and writes eval/scratch/holds.sql, which wrangler runs:
  npx wrangler d1 execute AUDIT_DB --remote --file ../eval/scratch/holds.sql   (from worker/)
Releasing the holds in Phase 4 is one statement:
  DELETE FROM screen_holds WHERE reason = 'eval_test_set'
"""
import argparse
import json
import os
import re
import time

EXPECTED = 60
VERSION_ID = re.compile(r"^068[A-Za-z0-9]{15}$")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--load-result", default="eval/test/load_result.json")
    p.add_argument("--out", default="eval/scratch/holds.sql")
    args = p.parse_args()

    with open(args.load_result, encoding="utf-8") as f:
        entries = json.load(f)
    ids = sorted({e["content_version_id"] for e in entries})

    # Validated before they go anywhere near SQL: only real-looking ContentVersion IDs, and exactly the test set.
    bad = [i for i in ids if not VERSION_ID.match(i)]
    if bad:
        raise SystemExit(f"Refusing: {len(bad)} IDs don't look like ContentVersion IDs")
    if len(ids) != EXPECTED:
        raise SystemExit(f"Refusing: expected {EXPECTED} distinct versions, found {len(ids)}")

    now = int(time.time())
    values = ",\n".join(f"  ('{i}', 'eval_test_set', {now})" for i in ids)
    sql = (
        "-- Generated by eval/hold_test_set.py. Holds the eval test set until Phase 4.\n"
        "INSERT OR IGNORE INTO screen_holds (content_version_id, reason, held_at) VALUES\n"
        f"{values};\n"
    )

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(sql)
    print(f"Wrote {len(ids)} holds to {args.out}")


if __name__ == "__main__":
    main()
    